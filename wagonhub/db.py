class PostgresConnection:
    """Keep the existing positional SQL API usable with psycopg."""

    def __init__(self):
        self.raw = psycopg.connect(DATABASE_URL, autocommit=True, row_factory=dict_row)

    def execute(self, query, parameters=()):
        return self.raw.execute(query.replace('?', '%s'), parameters)

    def commit(self):
        self.raw.execute('COMMIT')

    def rollback(self):
        self.raw.execute('ROLLBACK')

    def close(self):
        self.raw.close()


def connect():
    if DATABASE_URL:
        return PostgresConnection()
    if os.environ.get('VERCEL'):
        raise RuntimeError('Для Vercel задайте DATABASE_URL внешней PostgreSQL базы')
    path = Path(DB_PATH)
    path.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(path, timeout=10, isolation_level=None)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA foreign_keys=ON")
    con.execute("PRAGMA busy_timeout=10000")
    return con


def init_db():
    with closing(connect()) as con:
        if DATABASE_URL:
            for statement in POSTGRES_SCHEMA.split(';'):
                if statement.strip():
                    con.execute(statement)
        else:
            con.executescript(SCHEMA)


def insert_id(con, query, parameters):
    if DATABASE_URL:
        return con.execute(query + ' RETURNING id', parameters).fetchone()['id']
    return con.execute(query, parameters).lastrowid


def lock_listing(con, listing_id):
    """Serialize capacity decisions on a shared PostgreSQL listing."""
    if DATABASE_URL:
        con.execute('SELECT id FROM listings WHERE id=? FOR UPDATE', (listing_id,))


@contextmanager
def transaction():
    con = connect()
    try:
        con.execute("BEGIN" if DATABASE_URL else "BEGIN IMMEDIATE")
        yield con
        con.commit()
    except Exception:
        con.rollback()
        raise
    finally:
        con.close()
