"""SQLite for local runs, PostgreSQL for Vercel. One connection per operation."""
import os
import sqlite3
from contextlib import contextmanager, closing
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

DB_PATH = os.environ.get("DATABASE_PATH", str(Path(os.environ.get("DATA_DIR", ".")) / "wagonhub.db"))
DATABASE_URL = os.environ.get("DATABASE_URL", "")
INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.errors.UniqueViolation)

